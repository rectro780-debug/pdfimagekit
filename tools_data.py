# ------------------------------------------------------------ keyword variants
def variant(base_id, **kw):
    base = next(t for t in BASE if t["id"] == base_id)
    v = {**base, "main": False}
    v.update(kw)
    return v


def with_default(opts, name, value):
    return [{**o, "value": value} if o["name"] == name else o for o in opts]


